"""
FILE:         scripts/generate_dataset.py
WHAT IT DOES: THE MAIN DATASET SCRIPT. Creates the fictional company's documents and all
              the files that describe them.
WHERE IT FITS: Phase 2. Run it once; everything it writes is deterministic (same output
              every time), so it is safe to re-run.
USED BY:      you, from the command line; tests/unit/test_dataset.py calls generate().

    python -m scripts.generate_dataset

Pipeline (each step is labelled in generate() below):
    STEP 1  employees.build_roster()       -> 33 fictional employees
    STEP 2  content.build_documents()      -> 18 document specs + 21 golden Q&A facts
    STEP 3  render.write_pdf/docx/xlsx     -> data/raw/<category>/...      (the documents)
    STEP 4  manifest                        -> data/raw/manifest.yaml       (each doc's ACL)
    STEP 5  golden Q&A                      -> data/eval/golden_qa.yaml     (answer key)
    STEP 6  validate + access matrix        -> data/ACCESS_MATRIX.md        (who sees what)
"""

import argparse
from dataclasses import asdict
from pathlib import Path

import yaml

from app.auth.personas import load_personas
from app.core.access import can_read
from app.core.config import DATA_DIR
from app.ingestion.manifest import Manifest, load_manifest
from scripts.dataset.content import COMPANY, DocSpec, GoldenQA, build_documents
from scripts.dataset.employees import build_roster
from scripts.dataset.render import write_docx, write_pdf, write_xlsx

# Put at the top of every generated YAML so nobody hand-edits it.
GENERATED_HEADER = (
    "# GENERATED by scripts/generate_dataset.py - edit the generator, not this file.\n"
)


# =============================================================================
# HELPERS
# =============================================================================
# Pick the right writer for the file type (.pdf / .docx / .xlsx).
def _write_document(raw_dir: Path, doc: DocSpec) -> None:
    path = raw_dir / doc.path
    if doc.source_type == "pdf":
        write_pdf(path, doc.title, doc.banner, doc.blocks)
    elif doc.source_type == "docx":
        write_docx(path, doc.title, doc.banner, doc.blocks)
    else:
        write_xlsx(path, doc.title, doc.banner, doc.sheets)


def _write_yaml(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(GENERATED_HEADER + body, encoding="utf-8")


# Build ACCESS_MATRIX.md: run can_read() for every (persona, document) pair.
def _access_matrix(manifest: Manifest) -> str:
    personas = list(load_personas().values())

    # --- Part A: the main table (one row per document, one column per persona) ---
    lines = [
        "# Access Matrix",
        "",
        "Generated by `scripts/generate_dataset.py` from `data/raw/manifest.yaml` and",
        "`data/org/personas.yaml` using the reference policy in `app/core/access.py`.",
        "",
        "Y = may read the document. Column-level restrictions are listed under the table.",
        "",
        "| Document | Clearance | Departments | " + " | ".join(p.user_id for p in personas) + " |",
        "|---|---|---|" + "---|" * len(personas),
    ]
    for doc in manifest.documents:
        cells = ["Y" if can_read(p, doc) else "-" for p in personas]
        depts = ", ".join(str(d) for d in doc.departments)
        lines.append(f"| `{doc.doc_id}` | {int(doc.clearance_level)} | {depts} | "
                     + " | ".join(cells) + " |")

    # --- Part B: column rules (must pass BOTH the document and the column check) ---
    lines += ["", "## Column-level restrictions", ""]
    for doc in manifest.documents:
        for policy in doc.column_policies:
            readers = [p.user_id for p in personas if can_read(p, doc) and can_read(p, policy)]
            lines.append(f"- `{doc.doc_id}` columns {policy.columns}: "
                         f"only {', '.join(readers)}")

    # --- Part C: named grants, named blocks, and test-fixture tags ---
    lines += ["", "## Special cases", ""]
    for doc in manifest.documents:
        if doc.allowed_users:
            lines.append(f"- `{doc.doc_id}`: explicitly granted to {doc.allowed_users}")
        if doc.denied_users:
            lines.append(f"- `{doc.doc_id}`: explicitly denied to {doc.denied_users}")
        if doc.tags:
            lines.append(f"- `{doc.doc_id}`: tags {doc.tags}")
    return "\n".join(lines) + "\n"


# =============================================================================
# MAIN PIPELINE
# =============================================================================
def generate(data_dir: Path = DATA_DIR) -> tuple[Manifest, list[GoldenQA]]:
    raw_dir = data_dir / "raw"

    # STEP 1 + 2: build the employee roster, then every document's content and facts.
    docs, golden = build_documents(build_roster())

    # STEP 3: write each document to disk as a real PDF / DOCX / XLSX file.
    for doc in docs:
        _write_document(raw_dir, doc)

    # STEP 4: write the manifest - one access-label entry per document.
    manifest_path = raw_dir / "manifest.yaml"
    _write_yaml(manifest_path, {"company": COMPANY,
                                "documents": [d.manifest_entry() for d in docs]})

    # STEP 5: write the golden Q&A answer key (used by evals in Phase 11).
    _write_yaml(data_dir / "eval" / "golden_qa.yaml", {"questions": [asdict(q) for q in golden]})

    # STEP 6: re-load the manifest through the real loader (validates schema and that
    # every file exists), then write the human-readable access matrix.
    manifest = load_manifest(manifest_path)
    (data_dir / "ACCESS_MATRIX.md").write_text(_access_matrix(manifest), encoding="utf-8")
    return manifest, golden


# =============================================================================
# COMMAND-LINE ENTRY POINT
# =============================================================================
def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the synthetic Orbitra dataset.")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    args = parser.parse_args()
    manifest, golden = generate(args.data_dir)
    print(f"Wrote {len(manifest.documents)} documents and {len(golden)} golden questions "
          f"to {args.data_dir}")


if __name__ == "__main__":
    main()
